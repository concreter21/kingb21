const AdminPage = () => {
  const { adminToken, setAdminToken } = useSettings();
  const [tab, setTab] = useState("users");
  const navigate = useNavigate();

  if (!adminToken) return <TwoFAGate onSuccess={setAdminToken} />;

  const tabs = [
    { key: "users", label: "Users", icon: Users, node: <UsersTab /> },
    { key: "audit", label: "Deleted Audit", icon: History, node: <AuditTab /> },
    { key: "unfiled", label: "Unfiled Footage", icon: Camera, node: <UnfiledTab /> },
    { key: "branding", label: "Branding", icon: Palette, node: <BrandingTab /> },
  ];

  return (
    <DashboardLayout
      title="Admin Panel"
      subtitle="Users, audit trail, unfiled footage & branding"
      action={
        <button
          onClick={() => { setAdminToken(null); navigate("/dashboard/settings"); }}
          className="inline-flex items-center gap-1.5 h-9 px-3 rounded-lg bg-white border border-slate-200 hover:border-slate-300 text-slate-700 text-[13px] font-medium"
        >
          <LogOut className="w-3.5 h-3.5" /> Sign out admin
        </button>
      }
    >
      <div className="flex items-center gap-1 mb-4 border-b border-slate-200">
        {tabs.map((t) => (
          <button
            key={t.key}
            onClick={() => setTab(t.key)}
            className={`h-10 px-4 text-[13px] font-medium border-b-2 transition-colors inline-flex items-center gap-1.5 ${
              tab === t.key
                ? "border-brand-700 text-brand-700"
                : "border-transparent text-slate-600 hover:text-slate-900"
            }`}
          >
            <t.icon className="w-3.5 h-3.5" />
            {t.label}
          </button>
        ))}
      </div>
      {tabs.find((t) => t.key === tab)?.node}
    </DashboardLayout>
  );
};

export default AdminPage;
